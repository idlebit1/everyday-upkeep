export type PresetCategory =
  | "home"
  | "kitchen"
  | "personal"
  | "vehicle"
  | "wardrobe"
  | "equipment"
  | "tools"
  | "yard"
  | "pets"
  | "other";

export interface UpkeepPreset {
  id: string;
  title: string;
  category: PresetCategory;
  shortDescription: string;
  defaultCadence: TimeCadence | UsageCadence;
  // Optional secondary cadence — when set, the item should be treated as
  // "whichever comes first" against the default cadence. Used for items
  // like oil changes that age by both time and use.
  secondaryCadence?: TimeCadence | UsageCadence;
  onboardingRank?: number; // lower = shown first in onboarding. undefined = not shown in onboarding
  tags: string[];
}

interface TimeCadence {
  type: "time";
  interval: number;
  unit: "days" | "weeks" | "months" | "years";
}

interface UsageCadence {
  type: "usage";
  unit: string;
  threshold: number;
}

